import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Accounts } from '../cloud/accounts.mjs';
import { Runs } from '../cloud/runs.mjs';
if (!process.env.CORILO_TEST_DATABASE_URL) throw new Error('CORILO_TEST_DATABASE_URL must point to a disposable PostgreSQL database');
const limits = { maxRunning: 1, maxQueued: 2, leaseSeconds: 30, maxRunSeconds: 120 };

test('persistent run ownership, idempotency, capacity, stop and fenced recovery with real PostgreSQL', async t => {
  const accounts = new Accounts(process.env.CORILO_TEST_DATABASE_URL);
  t.after(() => accounts.close());
  await accounts.migrate(); await accounts.migrate();
  const runs = new Runs(accounts.pool, limits);
  const owner = async () => {
    const email = randomUUID()+'@example.test';
    const session = await accounts.login({ subject: randomUUID(), email }, await accounts.invite(email));
    return (await accounts.session(session)).id;
  };
  const a = await owner(), b = await owner(), c = await owner();
  const ca = await runs.conversation(a), cb = await runs.conversation(b), cc = await runs.conversation(c);
  assert.equal(await runs.conversation(a, ca), ca);
  await assert.rejects(runs.conversation(b, ca), e => e.status === 404);
  await assert.rejects(runs.submit(b, { conversationId: ca, key: 'cross', prompt: 'private' }), e => e.status === 404);
  assert.throws(() => new Runs(accounts.pool), /Invalid/);
  const input = { conversationId: ca, key: 'request-a', prompt: '保留原文\n整理笔记' };
  const [r1, r2] = await Promise.all([runs.submit(a, input), runs.submit(a, input)]);
  assert.equal(r1.id, r2.id); assert.equal(r1.state, 'queued');
  assert.equal((await runs.events(a, r1.id)).length, 1);
  await assert.rejects(runs.submit(a, { ...input, prompt: 'different' }), e => e.status === 409);
  await assert.rejects(runs.submit(a, { ...input, key: 'new-key' }), e => e.status === 409);
  for (const operation of [() => runs.get(b, r1.id), () => runs.events(b, r1.id), () => runs.stop(b, r1.id)])
    await assert.rejects(operation(), e => e.status === 404);
  const rb = await runs.submit(b, { conversationId: cb, key: 'b', prompt: 'B' });
  await assert.rejects(runs.submit(c, { conversationId: cc, key: 'c', prompt: 'C' }), e => e.status === 429);
  const claims = await Promise.all([runs.claim(), runs.claim()]);
  assert.equal(claims.filter(Boolean).length, 1);
  const claim = claims.find(Boolean);
  assert.equal(claim.id, r1.id);
  assert.equal(claim.prompt, input.prompt);
  assert.equal((await accounts.pool.query('SELECT lease_digest FROM corilo_private.runs WHERE id=$1', [claim.id])).rows[0].lease_digest === claim.token, false);
  assert.equal((await runs.get(a, claim.id)).token, undefined);
  assert.equal((await runs.get(a, claim.id)).prompt, undefined);
  assert.deepEqual(await runs.heartbeat(claim.id, claim.token), { continue: true });
  await assert.rejects(runs.heartbeat(claim.id, '0'.repeat(64)), e => e.status === 409);
  assert.equal((await runs.stop(a, claim.id)).state, 'stopping');
  assert.deepEqual(await runs.heartbeat(claim.id, claim.token), { continue: false });
  assert.equal(await runs.claim(), null, 'stopping worker retains its global slot');
  await assert.rejects(runs.reconcile(claim.id, async () => false), e => e.status === 503);
  assert.equal((await runs.get(a, claim.id)).state, 'stopping');
  let stopped;
  const stoppedRun = await runs.reconcile(claim.id, async id => { stopped = id; return true; });
  assert.equal(stopped, claim.workerId); assert.equal(stoppedRun.state, 'stopped');
  await assert.rejects(runs.heartbeat(claim.id, claim.token), e => e.status === 409);
  assert.equal((await runs.submit(a, input)).id, claim.id, 'retry after stopping must not replay');
  assert.deepEqual((await runs.events(a, claim.id)).map(e => e.state), ['queued','running','stopping','stopped']);
  const events = await runs.events(a, claim.id);
  assert.equal((await runs.events(a, claim.id, events[1].id)).length, 2);
  // Recreate the service and its DB pool: persisted work is read, not resubmitted.
  const reopened = new Accounts(process.env.CORILO_TEST_DATABASE_URL); t.after(() => reopened.close());
  const resumed = new Runs(reopened.pool, limits);
  assert.equal((await resumed.get(b, rb.id)).state, 'queued');
  const bClaim = await resumed.claim(); assert.equal(bClaim.id, rb.id);
  await accounts.pool.query("UPDATE corilo_private.runs SET lease_until=now()-interval '1 second' WHERE id=$1", [rb.id]);
  assert.deepEqual(await resumed.heartbeat(rb.id, bClaim.token), { continue: false }, 'expired lease cannot be renewed');
  assert.equal(await resumed.claim(), null, 'expired lease is not permission to start another worker');
  assert.ok((await resumed.recoveryCandidates()).some(row => row.id === rb.id));
  await assert.rejects(resumed.reconcile(rb.id, async () => { throw new Error('stop unavailable'); }), /stop unavailable/);
  assert.equal((await resumed.get(b, rb.id)).state, 'stopping');
  assert.equal((await resumed.reconcile(rb.id, async () => true)).state, 'interrupted');
  await assert.rejects(resumed.finish(rb.id, bClaim.token, 'completed'), e => e.status === 409);
  assert.equal(await resumed.claim(), null, 'interrupted run is never requeued');
  const rc = await resumed.submit(c, { conversationId: cc, key: 'c', prompt: 'C' });
  assert.equal((await resumed.stop(c, rc.id)).state, 'stopped');
  assert.equal(await resumed.claim(), null, 'queued cancellation never starts a worker');
  // Hard deadline is independent of lease heartbeats; stop after exit cannot claim success.
  const next = await resumed.submit(a, { ...input, key: 'next' });
  const nextClaim = await resumed.claim();
  await accounts.pool.query("UPDATE corilo_private.runs SET deadline_at=now()-interval '1 second' WHERE id=$1", [next.id]);
  assert.equal((await resumed.finish(next.id, nextClaim.token, 'completed')).state, 'interrupted');
  const normal = await resumed.submit(a, { ...input, key: 'normal' });
  const normalClaim = await resumed.claim();
  assert.equal((await resumed.finish(normal.id, normalClaim.token, 'completed')).state, 'completed');
  const stopRace = await resumed.submit(a, { ...input, key: 'stop-race' });
  const stopClaim = await resumed.claim();
  await resumed.stop(a, stopRace.id);
  assert.equal((await resumed.finish(stopRace.id, stopClaim.token, 'completed')).state, 'stopped', 'late completion cannot erase a committed stop request');
  const failed = await resumed.submit(a, { ...input, key: 'failed' });
  const failedClaim = await resumed.claim();
  assert.equal((await resumed.finish(failed.id, failedClaim.token, 'failed')).state, 'failed');
  const disabledRunning = await resumed.submit(b, { conversationId: cb, key: 'disabled-running', prompt: 'B' });
  const disabledClaim = await resumed.claim();
  const disabledQueued = await resumed.submit(c, { conversationId: cc, key: 'disabled-queued', prompt: 'C' });
  await accounts.pool.query('UPDATE corilo_private.accounts SET disabled=true WHERE id=ANY($1::uuid[])', [[b,c]]);
  await assert.rejects(resumed.get(b, disabledRunning.id), e => e.status === 403);
  assert.deepEqual(await resumed.heartbeat(disabledRunning.id, disabledClaim.token), { continue: false });
  assert.equal((await resumed.reconcile(disabledRunning.id, async () => true)).state, 'interrupted');
  assert.equal(await resumed.claim(), null);
  const disabledState = (await accounts.pool.query('SELECT state,reason FROM corilo_private.runs WHERE id=$1', [disabledQueued.id])).rows[0];
  assert.deepEqual(disabledState, { state: 'interrupted', reason: 'account_disabled' });
  // DB constraints independently reject cross-owner associations.
  await assert.rejects(accounts.pool.query('INSERT INTO corilo_private.conversations(id,owner_id,vault_id) SELECT $1,$2,vault_id FROM corilo_private.conversations WHERE id=$3',
    [randomUUID(), a, cb]), e => e.code === '23503');
});
