import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, access } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { Context } from '@deepseek-ai/cordis';
import Tools from '@deepseek-ai/dsh-tools';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import { ToolExecutionPipeline } from '@deepseek-ai/dsh-tools/pipeline';
import * as notes from '../index.mjs';

test('published Harness tools share versioned Git recovery, trash and restore', async t => {
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'corilo-recovery-pipeline-'));
  const root = path.join(temporary, 'notes'), stateRoot = path.join(temporary, 'state');
  const ctx = new Context();
  t.after(async () => { await ctx.fiber.dispose(); await rm(temporary, { recursive: true, force: true }); });
  await ctx.plugin(SystemPrompt); await ctx.plugin(Tools);
  const fiber = await ctx.plugin(notes, { root, stateRoot });
  assert.equal(ctx.tools.definitions().length, 14);
  const pipeline = new ToolExecutionPipeline(ctx);
  let id = 0;
  const call = async (suffix, args) => {
    const p = await pipeline.prepare({ callId: String(++id), name: `corilo_notes_${suffix}`, arguments: args, signal: new AbortController().signal });
    return pipeline.complete(p.exec, p.kind === 'dispatch' ? await pipeline.dispatch(p.exec) : p);
  };
  const create = await call('save', { path: '版本.md', text: '版本一', expected: null });
  assert.equal(create.isError, false);
  const update = await call('save', { path: '版本.md', text: '版本二', expected: create.value.version });
  assert.equal(update.isError, false);
  const history = await call('history', { path: '版本.md' });
  assert.equal(history.isError, false);
  const first = history.value.items.find(item => item.version === create.value.version);
  assert.ok(first, 'the first saved version is recoverable');
  const preview = await call('read_revision', { path: '版本.md', revision: first.revision });
  assert.equal(preview.value.text, '版本一');
  const stale = await call('restore_revision', { path: '版本.md', revision: first.revision, expected: create.value.version });
  assert.equal(stale.isError, true);
  assert.equal(await readFile(path.join(root, '版本.md'), 'utf8'), '版本二');
  const restored = await call('restore_revision', { path: '版本.md', revision: first.revision, expected: update.value.version });
  assert.equal(restored.isError, false);
  const trashed = await call('trash', { path: '版本.md', expected: restored.value.version });
  assert.equal(trashed.isError, false);
  await assert.rejects(access(path.join(root, '版本.md')));
  const list = await call('list_trash', {});
  assert.ok(list.value.items.some(item => item.id === trashed.value.id));
  const recovered = await call('restore_trash', { id: trashed.value.id, path: '恢复.md', expected: null });
  assert.equal(recovered.isError, false);
  assert.equal(await readFile(path.join(root, '恢复.md'), 'utf8'), '版本一');
  assert.equal((await call('read_revision', { path: '../secret.md', revision: first.revision })).isError, true);
  await fiber.dispose();
  assert.equal(ctx.tools.definitions().length, 0);
});
