// Select a closed set of official Astryx 0.7.11 static tokens. No React code,
// reset, global selectors, fonts or runtime dependencies are copied.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const version = '0.7.11';
const checkout = fileURLToPath(new URL('../', import.meta.url));
const [corePath, themePath] = process.argv.slice(2);
if (!corePath || !themePath || process.argv.length !== 4) throw Error('Usage: node scripts/vendor-astryx.mjs /absolute/core.css /absolute/theme.css');
const core = await readFile(corePath, 'utf8'), theme = await readFile(themePath, 'utf8');
if (!theme.includes(`Core: @astryxdesign/core@${version}`)) throw Error('Expected the pinned Astryx Neutral 0.7.11 stylesheet');
const sha = value => createHash('sha256').update(value).digest('hex');
const sourceHashes = { core: '846c350e7c8151d9a513a4804c2be54ad5c11b63038d27c3c2d835d540721b0c', theme: '88239be738a64af72ab767c9f71d72c80e540cc1bb476edb92bb41ad1bd9eafd' };
if (sha(core) !== sourceHashes.core || sha(theme) !== sourceHashes.theme) throw Error('Use the exact CSS assets from the pinned 0.7.11 npm tarballs');
const wanted = [
  'color-background-surface', 'color-background-body', 'color-background-card', 'color-background-muted',
  'color-accent', 'color-accent-muted', 'color-on-accent', 'color-neutral',
  'color-text-primary', 'color-text-secondary', 'color-text-disabled',
  'color-text-error', 'color-text-success', 'color-text-warning', 'color-text-info',
  'color-error-muted', 'color-success-muted', 'color-warning-muted', 'color-info-muted',
  'color-on-error-muted', 'color-on-success-muted', 'color-on-warning-muted', 'color-on-info-muted',
  'color-border', 'color-border-emphasized', 'color-overlay-hover', 'color-overlay-pressed',
  'radius-inner', 'radius-element', 'radius-container', 'radius-full',
  'text-heading-1-size', 'text-heading-1-weight', 'text-heading-1-leading',
  'text-heading-2-size', 'text-heading-2-weight', 'text-heading-2-leading',
  'text-body-size', 'text-body-weight', 'text-body-leading',
  'text-supporting-size', 'text-supporting-weight', 'text-supporting-leading',
  'font-weight-normal', 'font-weight-medium', 'font-weight-semibold',
  'duration-fast', 'shadow-low', ...Array.from({ length: 8 }, (_, i) => `spacing-${i + 1}`), 'spacing-10', 'spacing-12',
];
const tokens = new Map();
function collect(name) {
  if (tokens.has(name)) return;
  const pattern = new RegExp(`--${name}\\s*:\\s*([^;{}]+);`);
  const value = (theme.match(pattern) || core.match(pattern))?.[1].trim();
  if (!value) throw Error(`Missing official token: ${name}`);
  tokens.set(name, value);
  for (const dependency of value.matchAll(/var\(--([a-z0-9-]+)/g)) collect(dependency[1]);
}
wanted.forEach(collect);
const output = `/* Astryx Neutral ${version} static token subset, MIT, (c) 2026 Meta Platforms, Inc.
 * Source: @astryxdesign/theme-neutral@${version}/dist/theme.css
 * Source: @astryxdesign/core@${version}/dist/astryx.css
 * Theme SHA-256: ${sha(theme)}
 * Core SHA-256: ${sha(core)}
 * Generated by scripts/vendor-astryx.mjs. Values unchanged except --ax- prefix.
 * No React components, global reset, color-scheme override or webfonts included.
 * See THIRD_PARTY_NOTICES.md for license and compatibility boundary.
 */
:where(.CORILO_PLUGIN) {
${[...tokens].map(([name, value]) => `  --ax-${name}: ${value.replaceAll('var(--', 'var(--ax-')};`).join('\n')}
}
`;
for (const plugin of ['notes', 'todos']) await writeFile(path.join(checkout, 'plugins', plugin, 'client/astryx-tokens.css'), output.replace('.CORILO_PLUGIN', `.corilo-${plugin}`));
process.stdout.write(`Selected ${tokens.size} official tokens (${Buffer.byteLength(output)} bytes per independent plugin).\n`);
